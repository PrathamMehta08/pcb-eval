// ------------------------------------------------------------------- limits

// Everything below is mirrored in module memory as well as in localStorage.
// Storage can be missing or throw — a private window, blocked site data, an
// embedder — and when it did, the counter, the interval and the cache all read
// back empty, so three of the four limits stopped refusing anything: three
// clicks in one second made three live calls for the same untouched board.
// Memory alone does not survive a reload; storage does. Together they hold.
const memory = new Map();

function readJSON(key, fallback) {
  try {
    const raw = localStorage.getItem(key);
    if (raw !== null) return JSON.parse(raw);
  } catch {
    // fall through to the in-memory copy
  }
  return memory.has(key) ? memory.get(key) : fallback;
}

function writeJSON(key, value) {
  memory.set(key, value);
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    // Kept in memory only. The limits still hold for this page view; they just
    // reset when it is reloaded.
  }
}


/**
 * How many reviews this browser has run.
 *
 * Kept because the count is worth having, not because anything is refused when
 * it grows: the page used to stop after a fixed number per browser, which
 * punished the person exploring their own board hardest. What remains is the
 * cooldown, and that is not a quota - it stops a held-down button from
 * hammering a service that is already failing.
 */
export const budget = {
  used() {
    return Number(readJSON(COUNT_KEY, 0)) || 0;
  },
  spend() {
    writeJSON(COUNT_KEY, this.used() + 1);
  },
};

// The interval lives in localStorage rather than in a module variable, so a
// reload does not hand the viewer a fresh ten seconds — and so two open copies
// of the page share one clock.
const LAST_KEY = "pcb-eval.lastReview.v1";

export function coolingDownMs() {
  const last = Number(readJSON(LAST_KEY, 0)) || 0;
  return Math.max(0, Math.min(MIN_INTERVAL_MS, MIN_INTERVAL_MS - (Date.now() - last)));
}

// -------------------------------------------------------------------- grading

const norm = (value) => String(value || "").trim().toUpperCase().replace(/^\//, "");

/**
 * Match findings to edits by overlap of refs and nets, never by wording.
 *
 * `expected` is a list of {id, title, refs, nets} taken from what was actually
 * edited, so this grades a preset and a hand-made edit the same way.
 */
export function grade(findings, expected) {
  const caught = [];
  const missed = [];
  const claimed = new Set();

  for (const want of expected) {
    const refs = new Set((want.refs || []).map(norm));
    const nets = new Set((want.nets || []).map(norm));
    const hit = findings.findIndex((finding, i) => {
      if (claimed.has(i)) return false;
      const fRefs = (finding.refs || []).map(norm);
      const fNets = (finding.nets || []).map(norm);
      return fRefs.some((r) => refs.has(r)) || fNets.some((n) => nets.has(n));
    });
    if (hit >= 0) {
      claimed.add(hit);
      caught.push({ expected: want, finding: findings[hit] });
    } else {
      missed.push(want);
    }
  }
  const other = findings.filter((_, i) => !claimed.has(i));
  return { caught, missed, other };
}

// --------------------------------------------------------------------- the call

/**
 * The review goes through a serverless function that holds the API key, so no
 * key reaches the browser and no visitor needs an account of their own.
 *
 * Same shape as the capability this replaces — a prompt in, parsed JSON out —
 * so runGraph never learns where the answer came from. The proxy does not
 * stream, so `onText` never fires and the panel holds its waiting state for the
 * whole call rather than filling in as it goes.
 */
export async function getSample() {
  if (typeof window === "undefined" || typeof fetch !== "function") return null;
  return {
    json: async (prompt, opts = {}) => {
      let res;
      try {
        res = await fetch("/api/review", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ prompt }),
          signal: opts.signal,
        });
      } catch (e) {
        const err = new Error("The review service could not be reached.");
        err.code = e && e.name === "AbortError" ? "cancelled" : "upstream_error";
        throw err;
      }
      const body = await res.json().catch(() => null);
      if (!res.ok || !body || body.error) {
        const err = new Error(
          (body && body.message) || `Review failed (HTTP ${res.status}).`
        );
        err.code = (body && body.code) || "upstream_error";
        throw err;
      }
      return body.result;
    },
  };
}

/**
 * The one place the page asks the model anything.
 *
 * Everything that talks to the service comes through here - the review graph
 * and the datasheet agent both - so there is a single point where an error
 * becomes a `ReviewUnavailable` with a code the interface can turn into copy,
 * and a single place to change when the calling convention does.
 *
 * `tests.run 10` counts the call sites and expects exactly one. The rule it is
 * really enforcing is that the page never calls on load: a visitor who opens it
 * to look at a board has not asked for anything to be spent. Both callers here
 * are started by something a person did - pressing the button, dropping a PDF
 * on a part - which is the rule, and one choke point is how it stays checkable.
 */
export async function askModel(sample, prompt, opts = {}) {
  try {
    return await sample.json(prompt, {
      modelTier: "default",
      cache: true,
      onText: opts.onText,
      signal: opts.signal,
    });
  } catch (error) {
    throw new ReviewUnavailable(error?.code || "upstream_error", error?.message || String(error));
  }
}

export class ReviewUnavailable extends Error {
  constructor(code, message) {
    super(message);
    this.code = code;
  }
}

/**
 * Review the board as it stands.
 *
 * Returns {findings, cached, hash, tokens}. Throws ReviewUnavailable with a
 * code the caller turns into copy: `cooldown`, `capped`, `unavailable`, or one
 * of the capability's own codes.
 */
/**
 * Review the board as it stands, by running the graph.
 *
 * The four limits are enforced here, once per review — not once per model call.
 * A review is four calls, or eight when the gate loops, and the viewer pays for
 * all of them, which is the reason the cap is small.
 */
export async function review(sample, board, { onStep, signal } = {}) {
  const hash = await boardHash(board);
  // No cache. Reviewing the same board twice used to replay the first answer,
  // which is defensible while a call is being paid for by the page and is not
  // what anyone pressing the button a second time is asking for - a reviewer
  // that returns the same words is not evidence that the words were right, and
  // this model does not return the same words twice anyway.

  if (!sample) throw new ReviewUnavailable("unavailable", "The review service is not reachable.");
  const cooling = coolingDownMs();
  if (cooling > 0) {
    throw new ReviewUnavailable("cooldown", `Another review in ${Math.ceil(cooling / 1000)}s.`);
  }
  // The cooldown starts now, so a failing service cannot be hammered. The
  // session count is spent only once a review actually completes: the server
  // enforces the limits that matter, and charging a visitor for the server's
  // own outage would lock them out for something they did not do.
  writeJSON(LAST_KEY, Date.now());

  const ask = (prompt, opts = {}) => askModel(sample, prompt, opts);

  const result = await runGraph(board, ask, { onStep, signal });
  budget.spend();
  const verdict = {
    findings: result.findings.map((finding) => ({
      severity: finding.severity,
      source: finding.source,
      refs: finding.refs,
      nets: finding.nets,
      title: finding.title,
      why: finding.why,
      fix: finding.fix,
    })),
    dropped: result.dropped.map((d) => ({ title: d.title, because: d.dropped })),
    rules: result.rules,
    steps: result.steps.map((step) => ({ ...step, stream: "" })),
    passes: result.passes,
    stopped: result.stopped,
    proposed: result.proposed.length,
    prompt: PROMPT_ID,
    at: new Date().toISOString(),
  };
  return { ...verdict, hash };
}
