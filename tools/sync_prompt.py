"""Write the harness's single prompt into site/review.js, verbatim.

`baseline/single_prompt.py` and the page are supposed to be the same detector,
not two things that resemble each other — the README's "one prompt" column is
only a statement about the page if it sends the same prompt. So the page does
not keep its own copy: this generates it from `graph/prompts.py`, and
`tests/fixtures/distill.json` carries the Python's copy so the parity test
compares them character by character.

    python tools/sync_prompt.py            rewrite the block in site/review.js
    python tools/sync_prompt.py --check    exit non-zero if it is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from console import utf8  # noqa: E402
from graph.prompts import (  # noqa: E402
    BOARD_SLOT,
    SECOND_LOOK_JOB,
    SYSTEM,
    single_prompt_template,
)

REVIEW_JS = ROOT / "site" / "review.js"
BEGIN = "// >>> generated by tools/sync_prompt.py — do not edit by hand\n"
END = "// <<< generated\n"

HEADER = """// The prompts, byte for byte the ones the harness sends. They come from
// graph/prompts.py; this block is generated by tools/sync_prompt.py and the
// builder refuses to ship a stale copy. The page runs the same graph the
// numbers in the README came from, so the prompts have to be the same too.
"""


TAIL = """
/**
 * The one reviewer, given the whole distilled board.
 *
 * Keeps the name the parity tests know it by. What they assert through it is
 * the invariant that matters: the page sends the same prompt the flat-prompt
 * detector sends, so the README's comparison is a statement about this page.
 */
export function buildPrompt(distilled) {
  return SINGLE_PROMPT + distilled;
}

/**
 * The second look: the board again, plus the first pass's own findings.
 *
 * What it is shown is the reviewer's own output and nothing else - never the
 * rule findings, never a defect list. A second pass told where the
 * deterministic layer already looked is a second pass being handed the answer.
 */
export function secondLookPrompt(distilled, already) {
  const gap = String.fromCharCode(10);
  return SECOND_LOOK + distilled + gap + gap + "ALREADY REPORTED" + gap + already;
}

export { SYSTEM_PROMPT };
"""


def _js_array(name: str, text: str) -> str:
    """A long prompt as an array of lines, which stays readable in the source."""
    lines = ",\n".join(f"  {json.dumps(line)}" for line in text.split("\n"))
    return f"const {name} = [\n{lines},\n].join(\"\\n\");\n"


def _head_of(prompt: str) -> str:
    head, _, tail = prompt.partition(BOARD_SLOT)
    if tail:
        raise SystemExit("the board slot is no longer at the end of the prompt")
    return head


def block() -> str:
    parts = [
        BEGIN,
        HEADER,
        _js_array("SYSTEM_PROMPT", SYSTEM),
        "\n",
        _js_array("SINGLE_PROMPT", _head_of(single_prompt_template())),
        "\n",
        # The second look's job text. The board and the first pass's findings
        # are appended by the page, in that order.
        _js_array("SECOND_LOOK", _head_of(_second_look_template())),
        TAIL,
        END,
    ]
    return "".join(parts)


def _second_look_template() -> str:
    """The second-look job with the board slot where the board goes."""
    from graph.prompts import _build

    return _build(SECOND_LOOK_JOB, BOARD_SLOT)


def main() -> int:
    utf8()
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    source = REVIEW_JS.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r"[\s\S]*?" + re.escape(END))
    if not pattern.search(source):
        raise SystemExit(f"{REVIEW_JS} has no generated block to replace")

    updated = pattern.sub(lambda _: block(), source, count=1)
    if updated == source:
        print("site/review.js is up to date")
        return 0
    if args.check:
        print("site/review.js is out of date; run: python tools/sync_prompt.py")
        return 1
    REVIEW_JS.write_text(updated, encoding="utf-8")
    print(f"rewrote the prompt block in {REVIEW_JS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
